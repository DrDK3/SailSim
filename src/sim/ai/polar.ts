import { DEG } from '../math/angles';
import { knToMs, msToKn } from '../units';
import { hashNumbers } from '../hash';
import type { BoatParams } from '../boat/params';
import { uniformEnvironment } from '../env/environment';
import { Simulation } from '../simulation';
import { autopilotHelm } from '../control/autopilot';
import { aiSheetInput } from './sheets';

/**
 * Target speeds for the AI skippers: steady speed through the water at each true wind speed and angle, with
 * the AI's own settings (TWA autopilot, auto-trim on both sails, crew assist). MODEL OUTPUT from estimated
 * coefficients, not measured Squib performance; the AI uses it only to choose angles (best VMG up and down
 * wind) and to predict where it will be. Generated by `npm run ai:polar` into polarData.ts.
 */
export interface PolarData {
  /** Fingerprint of the boat parameters the table was computed with. */
  paramsHash: string;
  generated: string;
  twsKn: number[];
  twaDeg: number[];
  /** stwKn[i][j]: speed at twsKn[i], twaDeg[j]. */
  stwKn: number[][];
}

export const POLAR_TWS_KN = [3, 5, 7, 10, 13, 16, 20, 25];
export const POLAR_TWA_DEG = [25, 30, 34, 38, 42, 46, 50, 55, 60, 70, 80, 90, 105, 120, 135, 145, 155, 165, 172, 180];

/** Fingerprint of every number in the parameter set (order-stable). */
export function paramsFingerprint(p: BoatParams): string {
  const nums: number[] = [];
  const walk = (v: unknown) => {
    if (typeof v === 'number') nums.push(v);
    else if (typeof v === 'boolean') nums.push(v ? 1 : 0);
    else if (Array.isArray(v)) v.forEach(walk);
    else if (v && typeof v === 'object') for (const k of Object.keys(v).sort()) walk((v as Record<string, unknown>)[k]);
  };
  walk(p);
  return hashNumbers(nums);
}

/** Steady speed at one point, as the AI sails (TWA autopilot, auto-trim with heel-limited main). */
export function aiSteadySpeed(params: BoatParams, twsKn: number, twaDeg: number, durationS = 120): number {
  const sheets = { ease: 0 };
  const target = (twaDeg === 180 ? 179.5 : twaDeg) * DEG;
  const sim = new Simulation({
    params,
    env: uniformEnvironment({ twsKn, twdDeg: 0 }),
    initial: { headingDeg: -twaDeg, speedKn: 3 },
    input: { autoMain: true, autoJib: true, autoCrew: true },
    controller: (s) => ({ helm: autopilotHelm(s, { mode: 'twa', target }), ...aiSheetInput(s, sheets) }),
  });
  sim.advance(durationS);
  // Average over the last 20 s (a boat on the edge of control may oscillate).
  let sum = 0;
  for (let i = 0; i < 2000; i++) {
    sim.stepOnce();
    sum += Math.hypot(sim.state.u, sim.state.v);
  }
  return msToKn(sum / 2000);
}

export function computePolar(params: BoatParams, twsKn = POLAR_TWS_KN, twaDeg = POLAR_TWA_DEG, durationS = 120): PolarData {
  return {
    paramsHash: paramsFingerprint(params),
    generated: new Date().toISOString().slice(0, 10),
    twsKn,
    twaDeg,
    stwKn: twsKn.map((tws) => twaDeg.map((twa) => Math.round(aiSteadySpeed(params, tws, twa, durationS) * 1000) / 1000)),
  };
}

export interface AngleTarget {
  /** True wind angle (rad, positive). */
  twa: number;
  /** Speed through the water (m/s). */
  speed: number;
  /** Velocity made good towards (+) or away from the wind (m/s). */
  vmg: number;
}

/** Interpolating lookup on a PolarData table, with best upwind and downwind VMG angles per wind speed. */
export class Polar {
  private readonly beatRows: AngleTarget[];
  private readonly runRows: AngleTarget[];

  constructor(readonly data: PolarData) {
    this.beatRows = data.twsKn.map((_, i) => this.best(i, 1));
    this.runRows = data.twsKn.map((_, i) => this.best(i, -1));
  }

  private best(i: number, dir: 1 | -1): AngleTarget {
    // Search 0.5° steps along the interpolated row.
    let bestT: AngleTarget = { twa: 0, speed: 0, vmg: -Infinity };
    const lo = dir > 0 ? 25 : 90;
    const hi = dir > 0 ? 90 : 180;
    for (let a = lo; a <= hi; a += 0.5) {
      const s = knToMs(this.rowSpeed(i, a));
      const vmg = dir * s * Math.cos(a * DEG);
      if (vmg > bestT.vmg) bestT = { twa: a * DEG, speed: s, vmg };
    }
    return bestT;
  }

  private rowSpeed(i: number, twaDeg: number): number {
    const a = this.data.twaDeg;
    const row = this.data.stwKn[i]!;
    if (twaDeg <= a[0]!) return row[0]! * Math.max(0, (twaDeg - 15) / (a[0]! - 15));
    for (let j = 0; j < a.length - 1; j++) {
      if (twaDeg <= a[j + 1]!) {
        const f = (twaDeg - a[j]!) / (a[j + 1]! - a[j]!);
        return row[j]! * (1 - f) + row[j + 1]! * f;
      }
    }
    return row[row.length - 1]!;
  }

  private twsIndex(twsKn: number): { i: number; f: number } {
    const w = this.data.twsKn;
    if (twsKn <= w[0]!) return { i: 0, f: 0 };
    for (let i = 0; i < w.length - 1; i++) if (twsKn <= w[i + 1]!) return { i, f: (twsKn - w[i]!) / (w[i + 1]! - w[i]!) };
    return { i: w.length - 2, f: 1 };
  }

  /** Steady speed through the water (m/s) at true wind speed tws (m/s) and angle twa (rad, either sign). */
  speed(tws: number, twa: number): number {
    const kn = msToKn(tws);
    const deg = Math.min(180, Math.abs(twa) / DEG);
    const { i, f } = this.twsIndex(kn);
    let v = this.rowSpeed(i, deg) * (1 - f) + this.rowSpeed(i + 1, deg) * f;
    // Below the lowest tabulated wind speed, scale towards zero.
    if (kn < this.data.twsKn[0]!) v *= kn / this.data.twsKn[0]!;
    return knToMs(v);
  }

  private interp(rows: AngleTarget[], tws: number): AngleTarget {
    const { i, f } = this.twsIndex(msToKn(tws));
    const a = rows[i]!;
    const b = rows[i + 1]!;
    const twa = a.twa * (1 - f) + b.twa * f;
    const speed = this.speed(tws, twa);
    return { twa, speed, vmg: Math.abs(speed * Math.cos(twa)) };
  }

  /** Best upwind VMG angle and speed at a true wind speed (m/s). */
  beat(tws: number): AngleTarget {
    return this.interp(this.beatRows, tws);
  }

  /** Best downwind VMG angle and speed. */
  run(tws: number): AngleTarget {
    return this.interp(this.runRows, tws);
  }
}
