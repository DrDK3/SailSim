/**
 * Regenerate the AI target-speed tables from the current boat parameters. MODEL OUTPUT (estimated coefficients), not
 * measured Squib performance.
 *   npm run ai:polar              # src/sim/ai/polarData.ts: the boat without a spinnaker (AI_POLAR)
 *   npm run ai:polar -- --spin    # src/sim/ai/polarDataSpin.ts: the boat carrying one (AI_POLAR_SPIN), built on AI_POLAR
 */
import { writeFileSync } from 'node:fs';
import { computePolar, computeSpinPolar, type PolarData } from '../src/sim/ai/polar';
import { squibParams } from '../src/sim/boat/squib';
import { withSpinnaker } from '../src/sim/boat/spinnaker';
import { AI_POLAR } from '../src/sim/ai/polarData';

const spin = process.argv.includes('--spin');
const t0 = Date.now();
const data: PolarData = spin ? computeSpinPolar(AI_POLAR, withSpinnaker(squibParams())) : computePolar(squibParams());
const file = spin ? 'polarDataSpin.ts' : 'polarData.ts';
const name = spin ? 'AI_POLAR_SPIN' : 'AI_POLAR';
const what = spin
  ? '// AI target speeds for a boat carrying the spinnaker: MODEL OUTPUT (E) from estimated coefficients (auto-trim, TWA\n// autopilot, the crew trimming the spinnaker), built on AI_POLAR (each point aft of spinFromTwaDeg the faster of the two).'
  : '// AI target speeds: MODEL OUTPUT from estimated coefficients (auto-trim, TWA autopilot), not measured data.';
const body = `// GENERATED by tools/ai-polar.ts (npm run ai:polar${spin ? ' -- --spin' : ''}). Do not edit by hand.
${what}
import type { PolarData } from './polar';

export const ${name}: PolarData = ${JSON.stringify(data, null, 0).replace(/\],\[/g, '],\n  [')};
`;
writeFileSync(new URL(`../src/sim/ai/${file}`, import.meta.url), body);
console.log(`written src/sim/ai/${file} (${data.twsKn.length} x ${data.twaDeg.length} points, ${((Date.now() - t0) / 1000).toFixed(0)} s)`);
for (let i = 0; i < data.twsKn.length; i++) console.log(`${data.twsKn[i]} kn: ${data.stwKn[i]!.map((v, j) => v.toFixed(2) + (data.spinSet?.[i]?.[j] ? '*' : '')).join(' ')}`);
