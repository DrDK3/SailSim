/**
 * Regenerate the AI target-speed table (src/sim/ai/polarData.ts) from the current boat parameters.
 * MODEL OUTPUT (estimated coefficients), not measured Squib performance.   Usage: npm run ai:polar
 */
import { writeFileSync } from 'node:fs';
import { computePolar } from '../src/sim/ai/polar';
import { squibParams } from '../src/sim/boat/squib';

const t0 = Date.now();
const data = computePolar(squibParams());
const body = `// GENERATED by tools/ai-polar.ts (npm run ai:polar). Do not edit by hand.
// AI target speeds: MODEL OUTPUT from estimated coefficients (auto-trim, TWA autopilot), not measured data.
import type { PolarData } from './polar';

export const AI_POLAR: PolarData = ${JSON.stringify(data, null, 0).replace(/\],\[/g, '],\n  [')};
`;
writeFileSync(new URL('../src/sim/ai/polarData.ts', import.meta.url), body);
console.log(`written src/sim/ai/polarData.ts (${data.twsKn.length} x ${data.twaDeg.length} points, ${((Date.now() - t0) / 1000).toFixed(0)} s)`);
for (let i = 0; i < data.twsKn.length; i++) console.log(`${data.twsKn[i]} kn: ${data.stwKn[i]!.map((v) => v.toFixed(2)).join(' ')}`);
