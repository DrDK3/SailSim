/** Regenerate docs/PARAMETERS.md from the boat data files: npm run params */
import { writeFileSync } from 'node:fs';
import { SQUIB_TYPES, squibProvenance } from '../src/sim/boat/squib';

const { classSpec, calibration } = squibProvenance();
const fmt = (v: unknown) => (Array.isArray(v) ? `table (${v.length} rows)` : String(v));
const esc = (s?: string) => (s ?? '').replace(/\|/g, '\\|');
const table = (rows: typeof classSpec) =>
  ['| Parameter | Value | Unit | Tag | Source | Note |', '|---|---|---|---|---|---|', ...rows.map((r) => `| \`${r.path}\` | ${fmt(r.value)} | ${r.unit} | ${r.tag} | ${esc(r.source)} | ${esc(r.note)} |`)].join('\n');

const tagCounts = (rows: typeof classSpec) => {
  const n = new Map<string, number>();
  for (const r of rows) n.set(r.tag, (n.get(r.tag) ?? 0) + 1);
  return [...n].map(([t, k]) => `${k} tag ${t}`).join(', ');
};

const md = `# Boat parameters (generated)

Generated by \`npm run params\` from \`data/boats/squib/class-spec.json\`, \`calibration.json\` and \`variants.json\`.
Do not edit by hand. Tags: V verified (primary, inspected), S(p) primary document seen only via search excerpt,
S secondary, E estimated, N not established, C calibrated against named observations (docs/CALIBRATION.md).
Source ids refer to docs/SOURCES.md.

## Class data (${classSpec.length} parameters)

${table(classSpec)}

## Calibration coefficients (${calibration.length} parameters; ${tagCounts(calibration)})

${table(calibration)}

## Squib types (\`data/boats/squib/variants.json\`)

Each type is a hull build plus a sail package. The class is a strict one-design (same hull form and sail plan
for every builder, C10), so a type changes only the parameters listed; everything else is as above. The Rondar
type is the calibrated default.

${SQUIB_TYPES.map((t) => `### ${t.label}\n\nHull: ${t.hullLabel}. Sails: ${t.sailsLabel}.\n\n${t.summary}\n\n${t.differences.length ? table(t.differences) : 'No changes from the parameters above.'}`).join('\n\n')}
`;
writeFileSync('docs/PARAMETERS.md', md);
console.log(`docs/PARAMETERS.md: ${classSpec.length} class parameters, ${calibration.length} calibration parameters`);
